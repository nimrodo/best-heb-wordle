"""Find Construct forms in Hspell's morphology data (`nouns.hif`, `verbs.hif`).

Each line is `word tag,tag,...`. Hspell tags a reading `סמיכות` when the form can
be a construct form, but a homograph is listed twice, once plain and once tagged
(אוכלת, פשרות, גברת): those are complete words as they stand. A form with a tagged
noun or participle reading and no plain reading of its own is a Construct form
(אבטחת, אוהדי, רודפי). A tagged masculine singular shows nothing: it is spelled like
the plain word. Possessive nouns (של/אני) and past-tense verbs are other
words that merely share the spelling, so they do not count as plain.

Run by hand; the result is committed as `construct_forms.txt`, so the Solutions
build never needs the Hspell data. Forms Hspell lacks (זריחת) go to `blocklist.txt`.
"""

import argparse
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path

from wordlists.guesses import WORD_LENGTH, normalise

CONSTRUCT_TAG = "סמיכות"
POSSESSIVE_MARK = "של/"
PAST_TAG = "עבר"
# Hspell's own source encoding; the .hif files are not UTF-8.
HIF_ENCODING = "iso-8859-8"

HEADER = """\
# Construct forms (first word of a smichut) that cannot be Solutions.
# Generated by `wordlists-construct` from Hspell's nouns.hif and verbs.hif; do not
# hand-edit (add words Hspell lacks to blocklist.txt). One word per line.
"""


def _is_noun(tags: list[str]) -> bool:
    return "ע" in tags[:2]


def _is_verb(tags: list[str]) -> bool:
    return tags[0] == "פ"


def _is_adjective(tags: list[str]) -> bool:
    return tags[0] == "ת"


def _readings(*hif_texts: str) -> dict[str, list[list[str]]]:
    readings: dict[str, list[list[str]]] = defaultdict(list)
    for text in hif_texts:
        for line in text.splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            word, _, description = line.partition(" ")
            readings[normalise(word)].append(description.strip().split(","))
    return readings


def _is_plain(tags: list[str]) -> bool:
    """A reading that makes the spelling a complete word on its own."""
    if CONSTRUCT_TAG in tags or POSSESSIVE_MARK in ",".join(tags):
        return False
    if _is_verb(tags):
        return PAST_TAG not in tags
    return _is_noun(tags) or _is_adjective(tags)


def _shows_construct(tags: list[str]) -> bool:
    """A construct reading that is spelled differently from its plain form.

    A masculine singular is spelled the same in both states, so it shows nothing.
    """
    masculine_singular = "ז" in tags and "יחיד" in tags
    return (
        CONSTRUCT_TAG in tags
        and (_is_noun(tags) or _is_verb(tags))
        and not masculine_singular
    )


def _is_construct_only(readings: list[list[str]]) -> bool:
    return any(_shows_construct(tags) for tags in readings) and not any(
        _is_plain(tags) for tags in readings
    )


def construct_forms(nouns_hif: str, verbs_hif: str) -> list[str]:
    """The sorted 5-letter Construct forms, final letters normalised."""
    return sorted(
        word
        for word, readings in _readings(nouns_hif, verbs_hif).items()
        if len(word) == WORD_LENGTH and _is_construct_only(readings)
    )


def construct_list(words: Iterable[str]) -> str:
    return HEADER + "\n".join(words) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="List Construct forms from Hspell's morphology data."
    )
    parser.add_argument("--nouns", type=Path, required=True, help="nouns.hif")
    parser.add_argument("--verbs", type=Path, required=True, help="verbs.hif")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("construct_forms.txt"),
        help="word list to write (default construct_forms.txt)",
    )
    args = parser.parse_args()
    read = lambda path: path.read_text(encoding=HIF_ENCODING)
    words = construct_forms(read(args.nouns), read(args.verbs))
    args.out.write_text(construct_list(words), encoding="utf-8")
    print(f"Construct forms: {len(words)}")
